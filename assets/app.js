/* Guild Fishing Board — presentation only. Data comes from assets/data.js
   (generated by scripts/refresh.py). No dependencies, no build step. */
(function () {
  "use strict";

  var D = window.FOREVER_DATA;
  var C = window.BOARD_CONFIG || {};

  if (!D || !D.items) {
    document.body.innerHTML =
      '<div style="max-width:640px;margin:80px auto;font:15px system-ui;color:#e6edf3">' +
      "<h1>No data yet</h1><p>Run <code>python3 scripts/refresh.py</code> to generate " +
      "<code>assets/data.js</code>, then reload this page.</p></div>";
    return;
  }

  var items = D.items;
  var recipes = D.recipes || {};
  var zonesMeta = D.zones || [];

  var S = {
    mode: "catch",
    cut: Number(C.defaultCut || 5),
    zone: "",
    sort: "net",
    search: "",
    hideIlliquid: true,
    showAllZones: false
  };

  var $ = function (sel) { return document.querySelector(sel); };
  var esc = function (s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  };
  var isNum = function (v) { return typeof v === "number" && isFinite(v); };

  /* copper -> 1.4g / 9.2s / 76c */
  function money(c) {
    if (!isNum(c)) return "\u2014";
    var a = Math.abs(c);
    var s;
    if (a >= 10000) s = (c / 10000).toFixed(2).replace(/\.?0+$/, "") + "g";
    else if (a >= 100) s = (c / 100).toFixed(1).replace(/\.0$/, "") + "s";
    else s = Math.round(c) + "c";
    return s;
  }

  function signedMoney(c) {
    if (!isNum(c)) return "\u2014";
    return (c > 0 ? "+" : c < 0 ? "\u2212" : "") + money(Math.abs(c));
  }

  function ageHours() {
    var t = Date.parse(D.generated);
    if (!isFinite(t)) return 0;
    return Math.max(0, (Date.now() - t) / 36e5);
  }

  /* ---------------- build the play list ---------------- */

  function zoneList(keys) {
    var out = [];
    keys.forEach(function (k) {
      var it = items[k];
      if (!it || !it.zones) return;
      it.zones.forEach(function (z) { if (out.indexOf(z) === -1) out.push(z); });
    });
    return out;
  }

  function verdict(net, sold, pool) {
    if (!isNum(sold)) return ["unpriced", "grey"];
    if (sold < 25) return ["illiquid", "grey"];
    if (!isNum(net)) return ["unpriced", "grey"];
    if (net <= 0) return ["avoid", "red"];
    if (net >= 500 && sold >= 150) return ["core", "gold"];
    if (net >= 200 && sold >= 350) return ["strong", "green"];
    if (isNum(pool) && pool >= 2500) return ["volume", "blue"];
    return ["ok", "blue"];
  }

  var LABEL = {
    core: "CORE", strong: "STRONG", volume: "VOLUME",
    ok: "OK", illiquid: "ILLIQUID", avoid: "AVOID", unpriced: "UNPRICED"
  };

  function buildPlays() {
    var mul = 1 - S.cut / 100;
    var plays = [];
    var usedAsFish = {};

    Object.keys(recipes).forEach(function (outKey) {
      var rec = recipes[outKey] || {};
      var inputs = rec.inputs || [];
      var out = items[outKey];
      if (!out || !inputs.length) return;

      var primaryKey = (inputs.filter(function (i) { return i[2]; })[0] || inputs[0])[0];
      var primary = items[primaryKey];
      if (!primary) return;
      usedAsFish[primaryKey] = true;

      var boughtCost = 0, allCost = 0;
      inputs.forEach(function (pair) {
        var it = items[pair[0]];
        var v = it && isNum(it.buyout) ? it.buyout : 0;
        allCost += v * (pair[1] || 1);
        if (!pair[2]) boughtCost += v * (pair[1] || 1);
      });

      var hasOut = isNum(out.buyout);
      var revenue = hasOut ? out.buyout * mul : null;
      var cost = S.mode === "catch" ? boughtCost : allCost;
      var rawNet = isNum(primary.buyout) ? primary.buyout * mul : null;

      var net, sold, pool, fate, cookedPrice;
      if (hasOut) {
        net = revenue - cost;
        sold = out.sold;
        pool = out.buyout * (isNum(out.sold) ? out.sold : 0) * mul;
        cookedPrice = out.buyout;
        var delta = isNum(net) && isNum(rawNet) ? net - rawNet : null;
        fate = "&rarr; " + esc(out.name) +
          (isNum(delta)
            ? ' <span class="' + (delta >= 0 ? "pos" : "neg") + '">(' +
              signedMoney(delta) + " vs raw)</span>"
            : "");
      } else {
        net = rawNet;
        sold = primary.sold;
        pool = isNum(primary.buyout) && isNum(primary.sold)
          ? primary.buyout * primary.sold * mul : null;
        cookedPrice = null;
        fate = '<span class="dim">Cooked not priced &mdash; sell raw</span>';
      }

      var v = verdict(net, sold, pool);
      plays.push({
        name: primary.name,
        sub: primary.note || (primary.kind === "fish" ? primary.water : ""),
        outName: out.name,
        zones: zoneList(inputs.map(function (i) { return i[0]; })),
        skill: primary.skill,
        raw: primary.buyout,
        cooked: cookedPrice,
        fate: fate,
        net: net,
        sold: sold,
        pool: pool,
        verdict: v[0],
        tone: v[1],
        url: primary.url,
        recipeUrl: out.url
      });
    });

    /* catches and clam products with no tracked recipe */
    Object.keys(items).forEach(function (k) {
      var it = items[k];
      if (!it || usedAsFish[k]) return;
      if (it.kind === "cooked") return;
      if (it.kind === "reagent") return;
      if (!isNum(it.buyout)) return;

      var net = it.buyout * mul;
      var sold = it.sold;
      var pool = isNum(sold) ? it.buyout * sold * mul : null;
      var v = verdict(net, sold, pool);
      plays.push({
        name: it.name,
        sub: it.kind === "pearl" ? "per pearl \u00b7 rare from clams" :
             it.kind === "meat" ? "clam product" : (it.note || it.water || ""),
        outName: "",
        zones: it.zones || [],
        skill: it.skill,
        raw: it.buyout,
        cooked: null,
        fate: '<span class="dim">Sell raw</span>',
        net: net,
        sold: sold,
        pool: pool,
        verdict: v[0],
        tone: v[1],
        url: it.url,
        recipeUrl: ""
      });
    });

    return plays;
  }

  /* ---------------- filtering / sorting ---------------- */

  var ALL = [];

  function visible() {
    var q = S.search.trim().toLowerCase();
    return ALL.filter(function (p) {
      if (S.hideIlliquid && isNum(p.sold) && p.sold < 25) return false;
            if (S.zone && p.zones.indexOf(S.zone) === -1) return false;
      if (q) {
        var hay = (p.name + " " + p.outName + " " + p.zones.join(" ") + " " + p.sub).toLowerCase();
        if (hay.indexOf(q) === -1) return false;
      }
      return true;
    }).sort(function (a, b) {
      if (S.sort === "name") return a.name.localeCompare(b.name);
      var k = S.sort === "pool" ? "pool" : S.sort === "sold" ? "sold" : "net";
      var av = isNum(a[k]) ? a[k] : -1;
      var bv = isNum(b[k]) ? b[k] : -1;
      return bv - av;
    });
  }

  /* ---------------- render ---------------- */

  function renderHead() {
    var titleEl = document.getElementById("boardTitle");
    if (titleEl && C.guildName) titleEl.textContent = C.guildName;
    $("#guildTag").textContent = C.tagline || "WoW Forever \u00b7 fishing + cooking";
    $("#marketLabel").textContent = D.market || (C.market || "");
    var h = ageHours();
    $("#stamp").textContent = "Scanned " + (D.generated_display || "\u2014") +
      " \u00b7 " + (h < 1 ? "just now" : Math.round(h) + "h ago");

    var pulse = $("#pulse");
    pulse.className = "pulse " + (h > 8 ? "stale" : "live");
    pulse.title = h > 8 ? "Data is over 8h old" : "Data is fresh";

    var banner = $("#staleBanner");
    var msgs = [];
    if (h > 8) {
      msgs.push("<strong>This snapshot is " + Math.round(h) + "h old.</strong> " +
        "The scheduled refresh may not be running \u2014 check the repository's Actions tab, " +
        "or run <code>python3 scripts/refresh.py</code> and redeploy.");
    }
    if (D.failures) {
      msgs.push("<strong>" + D.failures + " item page(s) failed to fetch</strong> on the last run; " +
        "their previous prices are being carried forward.");
    }
    if (C.raidBanner) {
      var days = Math.ceil((Date.parse(C.raidDate) - Date.now()) / 864e5);
      if (days > 0 && days < 40) {
        msgs.push("<strong>" + days + " days to the Dec 9 raid unlock</strong> " +
          "(Hyjal Summit, Barrow Deeps, Onyxia's Lair). Stat food demand usually climbs into a tier.");
      }
    }
    banner.innerHTML = msgs.join("<br>");
    banner.classList.toggle("hidden", msgs.length === 0);
  }

  function renderKpis(list) {
    var liquid = list.filter(function (p) { return isNum(p.sold) && p.sold >= 100; });
    var best = liquid.slice().sort(function (a, b) { return (b.net || 0) - (a.net || 0); })[0];
    var big = list.slice().sort(function (a, b) { return (b.pool || 0) - (a.pool || 0); })[0];
    var deep = list.slice().sort(function (a, b) { return (b.sold || 0) - (a.sold || 0); })[0];
    var core = list.filter(function (p) { return p.verdict === "core"; }).length;
    var h = ageHours();

    var cards = [
      ["Best per unit", best ? money(best.net) : "\u2014",
        best ? best.name + (best.outName ? " \u2192 " + best.outName : "") : "no liquid picks"],
      ["Biggest market", big ? money(big.pool) + "/day" : "\u2014",
        big ? big.name : "no data"],
      ["Deepest demand", deep ? (deep.sold || 0).toLocaleString() + "/day" : "\u2014",
        deep ? deep.name : "no data"],
      ["Core plays", String(core), "net + durable volume"]
    ];

    $("#kpis").innerHTML = cards.map(function (c) {
      return '<div class="kpi"><span class="k">' + esc(c[0]) + '</span>' +
        '<span class="v">' + esc(c[1]) + '</span>' +
        '<span class="n">' + esc(c[2]) + "</span></div>";
    }).join("");

    $("#stamp").title = "Snapshot age";
    if (h > 0) $("#stamp").setAttribute("data-age", h.toFixed(1));
  }

  function renderTable() {
    var rows = visible();
    $("#rowCount").textContent = rows.length + " of " + ALL.length + " plays";

    var body = $("#plays").querySelector("tbody");
    if (!rows.length) {
      body.innerHTML = '<tr><td colspan="10" class="dim" style="padding:22px">' +
        "Nothing matches those filters.</td></tr>";
      return;
    }

    body.innerHTML = rows.map(function (p) {
      var where = p.zones.length
        ? esc(p.zones.slice(0, 3).join(", ")) +
          (p.zones.length > 3 ? ' <span class="dim">+' + (p.zones.length - 3) + "</span>" : "")
        : '<span class="dim">not recorded</span>';

      var netCls = !isNum(p.net) ? "dim" : p.net > 0 ? "pos" : "neg";
      var skill = isNum(p.skill)
        ? '<span class="chip skill">' + p.skill + "</span>"
        : '<span class="dim">\u2014</span>';

      return "<tr>" +
        '<td class="l"><span class="name"><a href="' + esc(p.url) + '" target="_blank" rel="noopener">' +
          esc(p.name) + "</a></span>" +
          (p.sub ? '<span class="sub-name">' + esc(p.sub) + "</span>" : "") + "</td>" +
        '<td class="l where">' + where + "</td>" +
        '<td class="r">' + skill + "</td>" +
        '<td class="r money">' + money(p.raw) + "</td>" +
        '<td class="l fate">' + p.fate + "</td>" +
        '<td class="r money">' + money(p.cooked) + "</td>" +
        '<td class="r money ' + netCls + '">' + signedMoney(p.net) + "</td>" +
        '<td class="r money">' + (isNum(p.sold) ? p.sold.toLocaleString() : "\u2014") + "</td>" +
        '<td class="r money dim">' + (isNum(p.pool) ? money(p.pool) : "\u2014") + "</td>" +
        '<td class="l"><span class="chip ' + p.tone + '">' + LABEL[p.verdict] + "</span></td>" +
        "</tr>";
    }).join("");
  }

  function renderZones() {
    var list = zonesMeta.filter(function (z) {
      return S.showAllZones || (z.tier || 9) <= 2;
    });

    var html = list.map(function (z) {
      var catches = (z.catches || []).map(function (k) { return items[k]; })
        .filter(function (it) { return it; })
        .sort(function (a, b) { return (b.buyout || 0) - (a.buyout || 0); })
        .slice(0, 6);

      var best = ALL.filter(function (p) {
        return p.zones.indexOf(z.name) !== -1 && isNum(p.net) && (!isNum(p.sold) || p.sold >= 25);
      }).sort(function (a, b) { return (b.net || 0) - (a.net || 0); })[0];

      return '<article class="zone">' +
        "<h3>" + esc(z.name) +
          '<span class="chip skill">skill ' + (z.skill == null ? "?" : z.skill) + "</span></h3>" +
        '<p class="hub">' + esc(z.hub) +
          ' <span class="chip ' + (z.access === "Alliance town" || z.access === "Alliance FP" ? "green" : "grey") + '">' +
          esc(z.access) + "</span></p>" +
        "<ul>" + catches.map(function (it) {
          return "<li><b>" + esc(it.name) + "</b> " + money(it.buyout) + "</li>";
        }).join("") + "</ul>" +
        (z.note ? '<p class="note">' + esc(z.note) + "</p>" : "") +
        (best ? '<p class="note"><b>' + esc(best.name) + "</b> best here: " +
          signedMoney(best.net) + "/unit</p>" : "") +
        "</article>";
    }).join("");

    $("#zones").innerHTML = html;
    $("#toggleZones").textContent = S.showAllZones ? "Show key zones" : "Show all zones";
  }

  function renderTraps() {
    var mul = 1 - S.cut / 100;
    var out = [];

    Object.keys(recipes).forEach(function (outKey) {
      var rec = recipes[outKey] || {};
      var o = items[outKey];
      if (!o || !isNum(o.buyout)) return;
      var primary = null;
      (rec.inputs || []).forEach(function (i) { if (i[2] && items[i[0]]) primary = items[i[0]]; });
      if (!primary || !isNum(primary.buyout)) return;

      var cost = 0;
      (rec.inputs || []).forEach(function (i) {
        var it = items[i[0]];
        if (it && isNum(it.buyout)) cost += it.buyout * (i[1] || 1);
      });
      var net = o.buyout * mul - cost;
      if (net < 0) {
        out.push("<b>" + esc(o.name) + "</b> loses " + money(Math.abs(net)) +
          " per craft \u2014 sell <b>" + esc(primary.name) + "</b> raw instead.");
      }
      if (isNum(o.sold) && o.sold < 25 && net > 300) {
        out.push("<b>" + esc(o.name) + "</b> shows a " + signedMoney(net) +
          " margin but only " + o.sold + " sold/day across the whole region \u2014 high margin, no buyers.");
      }
    });

    var padded = Object.keys(items).map(function (k) { return items[k]; })
      .filter(function (it) {
        return isNum(it.price) && isNum(it.buyout) && it.buyout > 0 && it.price > it.buyout * 1.35;
      })
      .sort(function (a, b) { return (b.price / b.buyout) - (a.price / a.buyout); })
      .slice(0, 3);

    if (padded.length) {
      out.push("Medians are padded on " + padded.map(function (it) {
        return "<b>" + esc(it.name) + "</b> (" + money(it.price) + " median vs " +
          money(it.buyout) + " buyout)";
      }).join(", ") + ". Price to the buyout, not the median.");
    }

    var diff = 15 - 5;
    out.push("Selling in Gadgetzan, Booty Bay or Everlook costs <b>" + diff +
      "% more</b> than a capital city. On a 9.8s stew that is roughly 1s a sale \u2014 hearth to Stormwind to list.");

    out.push("Clams are a bundle, not a fish: meat every time, pearls sometimes. " +
      "No drop rates exist, so treat the golden pearl as upside and the meat as the floor.");

    $("#traps").innerHTML = out.map(function (t) { return "<li>" + t + "</li>"; }).join("");
  }

  function renderModeHint() {
    $("#modeHint").textContent = S.mode === "catch"
      ? "Costs shown are only what you must buy (spices, water). Your own fishing time is not charged. Auction cut " + S.cut + "%."
      : "Costs include buying the fish itself, so this is the flipping margin. Auction cut " + S.cut + "%.";
  }

  function toast(msg) {
    var t = document.querySelector(".toast");
    if (!t) {
      t = document.createElement("div");
      t.className = "toast";
      document.body.appendChild(t);
    }
    t.textContent = msg;
    t.classList.add("show");
    clearTimeout(t._h);
    t._h = setTimeout(function () { t.classList.remove("show"); }, 2400);
  }

  function copyList() {
    var rows = visible().slice(0, 8);
    if (!rows.length) return toast("Nothing to copy");
    var lines = ["Guild fishing plan \u2014 " + (D.generated_display || "") +
      " (" + (D.market || "") + ")"];
    rows.forEach(function (p, i) {
      lines.push((i + 1) + ". " + p.name +
        (p.outName ? " \u2192 " + p.outName : "") +
        " \u2014 " + signedMoney(p.net) + "/unit \u00b7 " +
        (isNum(p.sold) ? p.sold : "?") + " sold/day \u00b7 " +
        (p.zones.slice(0, 2).join(", ") || "zone n/a"));
    });
    var text = lines.join("\n");
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(text).then(
        function () { toast("Copied " + rows.length + " plays"); },
        function () { fallbackCopy(text); }
      );
    } else fallbackCopy(text);
  }

  function fallbackCopy(text) {
    var ta = document.createElement("textarea");
    ta.value = text;
    ta.style.position = "fixed";
    ta.style.left = "-9999px";
    document.body.appendChild(ta);
    ta.select();
    try { document.execCommand("copy"); toast("Copied"); }
    catch (e) { toast("Copy failed"); }
    document.body.removeChild(ta);
  }

  /* ---------------- wiring ---------------- */

  function renderAll() {
    renderModeHint();
    renderTable();
    renderKpis(ALL);
    renderZones();
  }

  function init() {
    renderHead();

    var zoneSel = $("#zone");
    var names = [];
    zonesMeta.forEach(function (z) { names.push(z.name); });
    names.sort().forEach(function (n) {
      var o = document.createElement("option");
      o.value = n; o.textContent = n;
      zoneSel.appendChild(o);
    });

    $("#mode").value = S.mode;
    $("#cut").value = String(S.cut);
    $("#hideIlliquid").checked = S.hideIlliquid;

    $("#mode").addEventListener("change", function (e) {
      S.mode = e.target.value;
      ALL = buildPlays();
      renderAll();
      renderTraps();
    });
    $("#cut").addEventListener("change", function (e) {
      S.cut = Number(e.target.value);
      ALL = buildPlays();
      renderAll();
      renderTraps();
    });
    $("#zone").addEventListener("change", function (e) { S.zone = e.target.value; renderTable(); renderZones(); });
    $("#sort").addEventListener("change", function (e) { S.sort = e.target.value; renderTable(); });
    $("#search").addEventListener("input", function (e) { S.search = e.target.value; renderTable(); });
    $("#hideIlliquid").addEventListener("change", function (e) { S.hideIlliquid = e.target.checked; renderTable(); });
    $("#toggleZones").addEventListener("click", function () {
      S.showAllZones = !S.showAllZones;
      renderZones();
    });
    $("#copyList").addEventListener("click", copyList);

    ALL = buildPlays();
    renderAll();
    renderTraps();

    $("#buildInfo").textContent = "Board generated " + (D.generated_display || "\u2014") +
      " \u00b7 " + Object.keys(items).length + " tracked items \u00b7 " +
      (D.failures || 0) + " fetch failures";
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
})();
